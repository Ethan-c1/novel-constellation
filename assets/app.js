        // ★★★ 自定义双击检测函数 ★★★
        function onPointerDown(event) {
            window._pointerDownPos = { x: event.clientX, y: event.clientY };
            window._pointerDownTime = performance.now();
        }

        function onPointerUp(event) {
            const dt = performance.now() - window._pointerDownTime;
            const dx = event.clientX - window._pointerDownPos.x;
            const dy = event.clientY - window._pointerDownPos.y;
            const dist = Math.sqrt(dx*dx + dy*dy);
            if (dist > 10) {
                clickCount = 0;
                if (clickTimer) { clearTimeout(clickTimer); clickTimer = null; }
                return;
            }

            const now = performance.now();
            if (clickCount === 0) {
                clickCount = 1;
                lastClickTime = now;
                lastClickPos = { x: event.clientX, y: event.clientY };
                if (clickTimer) clearTimeout(clickTimer);
                clickTimer = setTimeout(() => {
                    clickCount = 0;
                    clickTimer = null;
                }, 300);
            } else {
                const timeDiff = now - lastClickTime;
                const posDiff = Math.sqrt(
                    Math.pow(event.clientX - lastClickPos.x, 2) +
                    Math.pow(event.clientY - lastClickPos.y, 2)
                );
                if (timeDiff < 300 && posDiff < 15) {
                    // 双击！
                    clickCount = 0;
                    if (clickTimer) { clearTimeout(clickTimer); clickTimer = null; }
                    console.log('双击检测触发！');
                    handleDoubleClick(event);
                } else {
                    clickCount = 1;
                    lastClickTime = now;
                    lastClickPos = { x: event.clientX, y: event.clientY };
                    if (clickTimer) clearTimeout(clickTimer);
                    clickTimer = setTimeout(() => {
                        clickCount = 0;
                        clickTimer = null;
                    }, 300);
                }
            }
        }

