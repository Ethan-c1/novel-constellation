        function mergeVisualLinks(links) {
            const mergedByPair = new Map();
            const unique = values => [...new Set(values.filter(Boolean).map(value => String(value).trim()).filter(Boolean))];

            links.forEach(link => {
                if (!link?.s || !link?.t || link.s === link.t) return;
                const pairKey = [String(link.s), String(link.t)].sort().join('\u0000');
                if (!mergedByPair.has(pairKey)) {
                    mergedByPair.set(pairKey, {
                        ...link,
                        phases: unique(Array.isArray(link.phases) ? link.phases : []),
                        evidence: unique(Array.isArray(link.evidence) ? link.evidence : []),
                        events: Array.isArray(link.events) ? [...link.events] : [],
                        _relations: unique([link.r]),
                        _stories: unique([link.story]),
                    });
                    return;
                }

                const merged = mergedByPair.get(pairKey);
                merged.w = Math.max(Number(merged.w) || 1, Number(link.w) || 1);
                merged.confidence = Math.max(Number(merged.confidence) || 0, Number(link.confidence) || 0);
                merged.phases = unique([...merged.phases, ...(Array.isArray(link.phases) ? link.phases : [])]);
                merged.evidence = unique([...merged.evidence, ...(Array.isArray(link.evidence) ? link.evidence : [])]);
                merged.events.push(...(Array.isArray(link.events) ? link.events : []));
                merged._relations = unique([...merged._relations, link.r]);
                merged._stories = unique([...merged._stories, link.story]);
            });

            return [...mergedByPair.values()].map(link => ({
                ...link,
                r: link._relations.join(' / '),
                story: link._stories.join('；'),
            }));
        }

        function fitCameraToGraph(nodes) {
            const validNodes = nodes.filter(node =>
                Number.isFinite(node.x) && Number.isFinite(node.y) && Number.isFinite(node.z)
            );
            if (!validNodes.length) return;

            const min = new THREE.Vector3(Infinity, Infinity, Infinity);
            const max = new THREE.Vector3(-Infinity, -Infinity, -Infinity);
            validNodes.forEach(node => {
                min.x = Math.min(min.x, node.x);
                min.y = Math.min(min.y, node.y);
                min.z = Math.min(min.z, node.z);
                max.x = Math.max(max.x, node.x);
                max.y = Math.max(max.y, node.y);
                max.z = Math.max(max.z, node.z);
            });

            const center = min.clone().add(max).multiplyScalar(0.5);
            const verticalFov = THREE.MathUtils.degToRad(camera.fov);
            const horizontalFov = 2 * Math.atan(Math.tan(verticalFov / 2) * camera.aspect);
            const tanHalfVertical = Math.tan(verticalFov / 2);
            const tanHalfHorizontal = Math.tan(horizontalFov / 2);
            const direction = new THREE.Vector3(0.8, 0.58, 0.8).normalize();
            const forward = direction.clone().negate();
            const right = new THREE.Vector3().crossVectors(forward, new THREE.Vector3(0, 1, 0));
            if (right.lengthSq() < 0.001) right.set(1, 0, 0);
            right.normalize();
            const up = new THREE.Vector3().crossVectors(right, forward).normalize();
            const offset = new THREE.Vector3();
            const worldMargin = validNodes.length <= 20 ? 10 : 14;
            let requiredDistance = 0;

            // 在相机水平/垂直坐标系中分别拟合，避免宽屏被 3D 外接球过度缩小。
            validNodes.forEach(node => {
                offset.set(node.x, node.y, node.z).sub(center);
                const towardCamera = offset.dot(direction);
                const horizontal = Math.abs(offset.dot(right)) + worldMargin;
                const vertical = Math.abs(offset.dot(up)) + worldMargin;
                requiredDistance = Math.max(
                    requiredDistance,
                    towardCamera + horizontal / tanHalfHorizontal,
                    towardCamera + vertical / tanHalfVertical
                );
            });
            const distance = THREE.MathUtils.clamp(
                requiredDistance * 1.08,
                70,
                2200
            );

            controls.target.copy(center);
            camera.position.copy(center).addScaledVector(direction, distance);
            camera.near = Math.max(0.1, distance / 500);
            camera.far = Math.max(5000, distance * 12);
            camera.updateProjectionMatrix();
            controls.update();
            _graphInitDist = distance;
        }

        function resolveProtagonistNodeId(result) {
            const nodes = Array.isArray(result?.nodes) ? result.nodes : [];
            if (!nodes.length) return null;

            const protagonist = String(result?.overview?.protagonist || '').trim();
            if (protagonist) {
                const matched = nodes.find(node => {
                    const aliases = Array.isArray(node.aliases) ? node.aliases : [];
                    return node.id === protagonist || node.name === protagonist || aliases.includes(protagonist);
                });
                if (matched) return matched.id;
            }

            // 后端未明确给出主角时，以关系数量和关系权重选出最核心人物。
            const scores = new Map(nodes.map(node => [node.id, 0]));
            (Array.isArray(result?.links) ? result.links : []).forEach(link => {
                const weight = Math.max(1, Number(link.w) || 1);
                if (scores.has(link.s)) scores.set(link.s, scores.get(link.s) + weight);
                if (scores.has(link.t)) scores.set(link.t, scores.get(link.t) + weight);
            });
            return nodes.reduce((best, node) =>
                scores.get(node.id) > scores.get(best.id) ? node : best
            , nodes[0]).id;
        }

        function sanitizeAnalysisResult(result) {
            const inputNodes = Array.isArray(result?.nodes) ? result.nodes : [];
            const inputLinks = Array.isArray(result?.links) ? result.links : [];
            const personNodes = inputNodes.filter(node =>
                node?.id && (!node.kind || ['person', 'human', 'character'].includes(String(node.kind).toLowerCase()))
            );
            const personIds = new Set(personNodes.map(node => node.id));
            const validLinks = inputLinks.filter(link =>
                link?.s && link?.t && link.s !== link.t
                && personIds.has(link.s) && personIds.has(link.t)
            );
            const connectedIds = new Set();
            validLinks.forEach(link => {
                connectedIds.add(link.s);
                connectedIds.add(link.t);
            });
            const nodes = personNodes.filter(node => connectedIds.has(node.id));
            const excludedNodes = inputNodes.filter(node => !connectedIds.has(node?.id));
            let protagonist = String(result?.overview?.protagonist || '').trim();
            if (!connectedIds.has(protagonist)) {
                const scores = new Map(nodes.map(node => [node.id, 0]));
                validLinks.forEach(link => {
                    const weight = Math.max(1, Number(link.w) || 1);
                    scores.set(link.s, (scores.get(link.s) || 0) + weight);
                    scores.set(link.t, (scores.get(link.t) || 0) + weight);
                });
                protagonist = nodes.reduce((best, node) =>
                    !best || scores.get(node.id) > scores.get(best.id) ? node : best
                , null)?.id || '';
            }
            const priorWarnings = Array.isArray(result?.overview?.warnings)
                ? result.overview.warnings
                : [];
            const warnings = [...priorWarnings];
            if (excludedNodes.length) {
                const names = excludedNodes.slice(0, 8).map(node => node?.name || node?.id).filter(Boolean);
                warnings.push(
                    `已隐藏 ${excludedNodes.length} 个非人物或无有效关系的孤立实体`
                    + (names.length ? `（${names.join('、')}${excludedNodes.length > names.length ? '等' : ''}）` : '')
                );
                console.info('已从关系图隐藏孤立/非人物实体:', excludedNodes.map(node => node?.name || node?.id));
            }
            return {
                ...result,
                nodes,
                links: validLinks,
                overview: {
                    ...(result.overview || {}),
                    total_entities: nodes.length,
                    total_relationships: validLinks.length,
                    protagonist,
                    warnings,
                    excluded_entities: excludedNodes.map(node => node?.name || node?.id).filter(Boolean),
                },
                schema_version: Math.max(3, Number(result.schema_version) || 0),
            };
        }

        function resolveBookTitle(result) {
            const overview = result?.overview || {};
            const explicitTitle = String(overview.book_title || result?.title || '').trim();
            if (explicitTitle) return explicitTitle;

            let sourceName = String(overview.source_name || '').trim();
            if (!sourceName || sourceName === '粘贴文本') return '小说人物关系图';
            sourceName = sourceName.replace(/\.(?:txt|md|markdown)$/i, '');
            sourceName = sourceName.replace(
                /(?:[_\s+.-]*(?:纯正文|正文|全文|完整版|精校版|校对版|utf[_-]?8|gbk))+$/i,
                ''
            ).trim();
            return sourceName || '小说人物关系图';
        }

        function assignDynamicBranchColors(result) {
            const nodes = Array.isArray(result?.nodes) ? result.nodes : [];
            const links = Array.isArray(result?.links) ? result.links : [];
            if (!nodes.length) return;

            const protagonistId = resolveProtagonistNodeId(result);
            const branchPalette = [
                '#4FC3F7', '#FF7043', '#81C784', '#EF5350',
                '#AB47BC', '#42A5F5', '#EC407A', '#26A69A',
                '#FFA726', '#7E57C2'
            ];
            const nodeIds = new Set(nodes.map(node => node.id));
            const adjacency = new Map(nodes.map(node => [node.id, []]));
            const weightedDegree = new Map(nodes.map(node => [node.id, 0]));

            links.forEach(link => {
                if (!nodeIds.has(link.s) || !nodeIds.has(link.t)) return;
                const weight = Math.max(1, Number(link.w) || 1);
                adjacency.get(link.s).push({ id: link.t, weight });
                adjacency.get(link.t).push({ id: link.s, weight });
                weightedDegree.set(link.s, weightedDegree.get(link.s) + weight);
                weightedDegree.set(link.t, weightedDegree.get(link.t) + weight);
            });

            // 选择关系度最高的角色作为各颜色分支的中心，再向相邻人物传播颜色。
            const seedCount = Math.min(branchPalette.length, Math.max(4, Math.ceil(Math.sqrt(nodes.length))));
            const seeds = nodes
                .filter(node => node.id !== protagonistId)
                .sort((a, b) => weightedDegree.get(b.id) - weightedDegree.get(a.id))
                .slice(0, seedCount);
            const owner = new Map();
            const queue = [];
            seeds.forEach((node, index) => {
                owner.set(node.id, index);
                queue.push(node.id);
            });

            for (let cursor = 0; cursor < queue.length; cursor++) {
                const currentId = queue[cursor];
                const branchIndex = owner.get(currentId);
                const neighbors = [...(adjacency.get(currentId) || [])].sort((a, b) => b.weight - a.weight);
                neighbors.forEach(neighbor => {
                    if (neighbor.id === protagonistId || owner.has(neighbor.id)) return;
                    owner.set(neighbor.id, branchIndex);
                    queue.push(neighbor.id);
                });
            }

            nodes.forEach((node, index) => {
                if (node.id === protagonistId) {
                    node.visualColor = '#FFD700';
                    return;
                }
                const branchIndex = owner.has(node.id) ? owner.get(node.id) : index;
                node.visualColor = branchPalette[branchIndex % branchPalette.length];
            });
        }

