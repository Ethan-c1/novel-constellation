        // ---------- 启动 ----------
        function startApp() {
            initScene();
            showEmptyGraphState();
            animate();
            initUI();
            initUploadPanel();
            console.log('双击任意节点可聚焦，请尝试！');

            // ---------- 本地背景音乐控制 ----------
            function pickRandomMusic() {
                const idx = Math.floor(Math.random() * MUSIC_LIST.length);
                const filename = MUSIC_LIST[idx];
                return 'music/' + encodeURIComponent(filename);
            }

            let bgmAudio = new Audio(pickRandomMusic());
            bgmAudio.loop = true;
            bgmAudio.volume = 0.4;
            let musicEnabled = true;
            let musicPlaying = false;
            let autoplayFallbackArmed = false;

            function playNextMusic() {
                bgmAudio.src = pickRandomMusic();
                if (musicEnabled) startMusic();
            }
            bgmAudio.addEventListener('ended', playNextMusic);

            // 音乐开关按钮
            const musicBtn = document.getElementById('toggle-music');
            function updateMusicButton() {
                musicBtn.textContent = musicEnabled ? '🔇 关闭音乐' : '🎵 开启音乐';
                musicBtn.style.background = musicEnabled ? 'rgba(255,107,107,0.25)' : '';
                musicBtn.title = musicEnabled && !musicPlaying
                    ? '音乐已默认开启，浏览器允许后将自动播放'
                    : '';
            }

            function disarmAutoplayFallback() {
                if (!autoplayFallbackArmed) return;
                document.removeEventListener('pointerdown', startMusic);
                document.removeEventListener('keydown', startMusic);
                autoplayFallbackArmed = false;
            }

            function armAutoplayFallback() {
                if (autoplayFallbackArmed || !musicEnabled) return;
                document.addEventListener('pointerdown', startMusic);
                document.addEventListener('keydown', startMusic);
                autoplayFallbackArmed = true;
            }

            async function startMusic() {
                if (!musicEnabled) return false;
                try {
                    await bgmAudio.play();
                    if (!musicEnabled) {
                        bgmAudio.pause();
                        return false;
                    }
                    musicPlaying = true;
                    disarmAutoplayFallback();
                    updateMusicButton();
                    return true;
                } catch (error) {
                    musicPlaying = false;
                    updateMusicButton();
                    return false;
                }
            }

            function toggleMusic() {
                musicEnabled = !musicEnabled;
                if (!musicEnabled) {
                    bgmAudio.pause();
                    musicPlaying = false;
                    disarmAutoplayFallback();
                } else {
                    startMusic().then(started => {
                        if (!started) armAutoplayFallback();
                    });
                }
                updateMusicButton();
            }
            musicBtn.addEventListener('click', toggleMusic);

            // 默认开启；若浏览器阻止无交互自动播放，则在第一次点击/按键时补播。
            updateMusicButton();
            startMusic().then(started => {
                if (!started) {
                    armAutoplayFallback();
                    console.log('背景音乐已默认开启，将在首次交互时开始播放');
                }
            });
        }

        // app.js 可能由 index.html 在 DOMContentLoaded 之后动态加载。
        // 此时事件不会再次触发，因此必须根据 readyState 立即启动。
        if (document.readyState === 'loading') {
            document.addEventListener('DOMContentLoaded', startApp, { once: true });
        } else {
            startApp();
        }
