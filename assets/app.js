        // ---------- 聚焦节点 ----------
        function focusOnNode(nodeId) {
            const obj = nodeObjects[nodeId];
            if (!obj) {
                console.warn(`节点 ${nodeId} 不存在`);
                return;
            }
            const pos = new THREE.Vector3();
            obj.getWorldPosition(pos);
            focusTarget = pos.clone();
            const connectionCount = linkMeshes.reduce((count, line) => (
                line.userData.source === nodeId || line.userData.target === nodeId ? count + 1 : count
            ), 0);
            let neighborhoodRadius = 0;
            linkMeshes.forEach(line => {
                if (line.userData.source !== nodeId && line.userData.target !== nodeId) return;
                const neighborId = line.userData.source === nodeId ? line.userData.target : line.userData.source;
                const neighborObject = nodeObjects[neighborId];
                if (!neighborObject) return;
                neighborObject.getWorldPosition(_focusNeighborPosition);
                neighborhoodRadius = Math.max(neighborhoodRadius, pos.distanceTo(_focusNeighborPosition));
            });
            const focusVerticalFov = THREE.MathUtils.degToRad(camera.fov);
            const focusHorizontalFov = 2 * Math.atan(Math.tan(focusVerticalFov / 2) * camera.aspect);
            const focusLimitingFov = Math.min(focusVerticalFov, focusHorizontalFov);
            const neighborhoodFitDistance = (neighborhoodRadius + 18) / Math.tan(focusLimitingFov / 2) * 1.08;
            focusCameraDistance = THREE.MathUtils.clamp(
                Math.max(165 + Math.sqrt(Math.max(1, connectionCount)) * 8, neighborhoodFitDistance),
                180,
                420
            );
            _focusViewDirection.subVectors(camera.position, controls.target);
            if (_focusViewDirection.lengthSq() < 0.001) {
                _focusViewDirection.set(0.45, 0.3, 1);
            }
            _focusViewDirection.normalize();
            isFocusing = true;
            focusOriginalAutoRotate = isAutoRotateEnabled;
            isAutoRotateEnabled = false;
            document.getElementById('toggle-rotate').textContent = '▶ 恢复旋转';
            // ★ 高亮该节点的所有连接线
            setFocusHighlight(nodeId);
            console.log(`聚焦目标位置: ${pos.x.toFixed(2)}, ${pos.y.toFixed(2)}, ${pos.z.toFixed(2)}`);
        }

