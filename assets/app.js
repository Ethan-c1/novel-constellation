        // ---------- 连线悬停检测（屏幕空间距离法）----------
        function pointToSegmentDist(px, py, ax, ay, bx, by) {
            const dx = bx - ax;
            const dy = by - ay;
            const lenSq = dx * dx + dy * dy;
            if (lenSq === 0) return Math.hypot(px - ax, py - ay);
            let t = ((px - ax) * dx + (py - ay) * dy) / lenSq;
            t = Math.max(0, Math.min(1, t));
            return Math.hypot(px - (ax + t * dx), py - (ay + t * dy));
        }

        function checkLineHover(mouseX, mouseY) {
            if (!focusedNodeId || highlightedLinkIndices.length === 0) return -1;
            let closestIdx = -1;
            let closestDist = 14; // 像素阈值

            for (const idx of highlightedLinkIndices) {
                const line = linkMeshes[idx];
                const positions = line.userData.positions;
                for (let offset = 0; offset < positions.length - 3; offset += 3) {
                    _projA.set(positions[offset], positions[offset + 1], positions[offset + 2]).project(camera);
                    _projB.set(positions[offset + 3], positions[offset + 4], positions[offset + 5]).project(camera);
                    const ax = (_projA.x * 0.5 + 0.5) * window.innerWidth;
                    const ay = (-_projA.y * 0.5 + 0.5) * window.innerHeight;
                    const bx = (_projB.x * 0.5 + 0.5) * window.innerWidth;
                    const by = (-_projB.y * 0.5 + 0.5) * window.innerHeight;
                    const dist = pointToSegmentDist(mouseX, mouseY, ax, ay, bx, by);
                    if (dist < closestDist) {
                        closestDist = dist;
                        closestIdx = idx;
                    }
                }
            }
            return closestIdx;
        }

