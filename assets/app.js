        function updateLabelVisibility() {
            if (focusedNodeId) return; // 聚焦模式下由 setFocusHighlight 管理标签
            const camDist = camera.position.distanceTo(controls.target);
            const ratio = camDist / _graphInitDist;
            // 远景只保留核心人物；拉近时逐级增加标签。只有跨档时才改 DOM。
            let tier;
            let visibleCount;
            if (showAllNodeLabels) {
                tier = 4;
                visibleCount = nodeLabelObjects.length;
            } else if (ratio > 0.78) { tier = 0; visibleCount = 70; }
            else if (ratio > 0.60) { tier = 1; visibleCount = 110; }
            else if (ratio > 0.45) { tier = 2; visibleCount = 170; }
            else { tier = 3; visibleCount = nodeLabelObjects.length; }
            if (tier === _labelTier) return;
            _labelTier = tier;
            for (let i = 0; i < nodeLabelObjects.length; i++) {
                const entry = nodeLabelObjects[i];
                entry.label.visible = entry.rank < visibleCount;
            }
        }

        // ---------- 动画 ----------
        function animate(now = performance.now()) {
            requestAnimationFrame(animate);

            const deltaSeconds = Math.min(Math.max((now - _lastFrameTime) / 1000, 0.001), 0.05);
            _lastFrameTime = now;

            updateFlowParticles(deltaSeconds);
            updateLabelVisibility();

            if (isFocusing && focusTarget) {
                _focusCameraTarget.copy(focusTarget)
                    .addScaledVector(_focusViewDirection, focusCameraDistance);
                camera.position.lerp(_focusCameraTarget, focusLerpSpeed);
                controls.target.lerp(focusTarget, focusLerpSpeed);
                if (camera.position.distanceTo(_focusCameraTarget) < 1 && controls.target.distanceTo(focusTarget) < 1) {
                    isFocusing = false;
                    focusTarget = null;
                    if (focusOriginalAutoRotate) {
                        isAutoRotateEnabled = true;
                        document.getElementById('toggle-rotate').textContent = '⏸ 停止旋转';
                    }
                }
            }

            if (!isFocusing) {
                autoRotateCamera(deltaSeconds);
            }

            bgColorTime += deltaSeconds * 0.06;
            const hue = 0.65 + 0.08 * Math.sin(bgColorTime);
            _bgColor.setHSL(hue, 0.6, 0.06);
            scene.background = _bgColor;

            if (starParticles) {
                starParticles.rotation.y += deltaSeconds * 0.009;
                starParticles.rotation.x += deltaSeconds * 0.003;
            }

            // 只有鼠标实际移动后才做射线检测；静止展示时不再周期性制造 GC 峰值。
            if (_hoverDirty) {
                _hoverDirty = false;
                const tip = document.getElementById('tooltip');
                const rTip = document.getElementById('relation-tooltip');
                const mouseX = window._mouseX || 0;
                const mouseY = window._mouseY || 0;
                _pointer.x = (mouseX / window.innerWidth) * 2 - 1;
                _pointer.y = -(mouseY / window.innerHeight) * 2 + 1;
                _raycaster.setFromCamera(_pointer, camera);

                const intersects = _raycaster.intersectObjects(nodeMeshList, true);

                // 先检查节点悬停
                const nodeHit = intersects.length > 0 ? intersects.find(item => item.object.userData && item.object.userData.node) : null;

                if (nodeHit) {
                    const node = nodeHit.object.userData.node;
                    tip.innerHTML = `<b>${escapeHtml(node.name)}</b><br/>📜 ${escapeHtml(node.desc || '暂无')}<br/>🏷️ ${escapeHtml(CATEGORIES[node.cat]?.name || '人物')}`;
                    tip.style.display = 'block';
                    tip.style.left = (mouseX + 15) + 'px';
                    tip.style.top = (mouseY - 10) + 'px';
                    rTip.style.display = 'none';
                    renderer.domElement.style.cursor = 'pointer';
                    _lastHoverNode = node;
                    _hoveredLinkIdx = -1;
                } else {
                    tip.style.display = 'none';
                    _lastHoverNode = null;

                    // 检查高亮连线悬停
                    if (focusedNodeId) {
                        const linkIdx = checkLineHover(mouseX, mouseY);
                        if (linkIdx >= 0) {
                            rTip.innerHTML = buildRelationStory(linkIdx);
                            rTip.style.display = 'block';
                            rTip.style.left = Math.min(mouseX + 15, window.innerWidth - 460) + 'px';
                            rTip.style.top = Math.min(mouseY + 15, window.innerHeight - 220) + 'px';
                            renderer.domElement.style.cursor = 'crosshair';
                            _hoveredLinkIdx = linkIdx;
                        } else {
                            rTip.style.display = 'none';
                            renderer.domElement.style.cursor = 'default';
                            _hoveredLinkIdx = -1;
                        }
                    } else {
                        rTip.style.display = 'none';
                        renderer.domElement.style.cursor = 'default';
                        _hoveredLinkIdx = -1;
                    }
                }
            }

            controls.update();
            composer.render();
            // 全量名字保留可读性，但把 DOM 标签刷新限制在约 30 FPS，让 WebGL 旋转保持顺滑。
            const labelInterval = showAllNodeLabels ? 32 : 16;
            if (labelRenderer && now - _lastLabelRenderTime >= labelInterval) {
                labelRenderer.render(scene, camera);
                _lastLabelRenderTime = now;
            }
        }

