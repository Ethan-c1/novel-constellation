        async function startAnalysis(input) {
            const analyzeBtn = document.getElementById('analyze-btn');
            const progressEl = document.getElementById('progress');
            const progressFill = document.getElementById('progress-fill');
            const progressText = document.getElementById('progress-text');
            const errorEl = document.getElementById('upload-error');

            analyzeBtn.disabled = true;
            analyzeBtn.textContent = '分析中...';
            progressEl.classList.add('visible');
            errorEl.style.display = 'none';
            progressFill.style.width = '0%';
            progressText.textContent = '上传文件中...';
            showEmptyGraphState('⏳ 正在分析小说，完成后显示人物关系图');

            try {
                const requestOptions = { method: 'POST' };
                if (input.file) {
                    const formData = new FormData();
                    formData.append('file', input.file);
                    requestOptions.body = formData;
                } else {
                    requestOptions.headers = { 'Content-Type': 'application/json' };
                    requestOptions.body = JSON.stringify({ text: input.text, title: input.title });
                }

                const resp = await fetch(`${API_BASE}/api/analyze`, requestOptions);

                const data = await resp.json().catch(() => null);

                if (!resp.ok || !data?.success) {
                    throw new Error(data?.error || `分析请求失败（HTTP ${resp.status}）`);
                }

                // 轮询进度
                const sessionId = data.session_id;
                progressText.textContent = '已提交，等待处理...';

                _pollTimer = setInterval(async () => {
                    try {
                        const statusResp = await fetch(`${API_BASE}/api/status/${sessionId}`);
                        const statusData = await statusResp.json().catch(() => null);

                        if (!statusResp.ok || !statusData?.success) {
                            throw new Error(statusData?.error || `查询分析进度失败（HTTP ${statusResp.status}）`);
                        }

                        progressFill.style.width = statusData.progress + '%';
                        progressText.textContent = statusData.message || '';

                        if (statusData.status === 'completed' && statusData.result) {
                            clearInterval(_pollTimer);
                            _pollTimer = null;
                            applyAnalysisResult(statusData.result);
                        } else if (statusData.status === 'failed') {
                            clearInterval(_pollTimer);
                            _pollTimer = null;
                            throw new Error(statusData.error || '分析失败');
                        }
                    } catch (e) {
                        if (_pollTimer) {
                            clearInterval(_pollTimer);
                            _pollTimer = null;
                        }
                        showUploadError(e.message);
                        resetAnalyzeBtn();
                    }
                }, 1500);

            } catch (e) {
                showUploadError(e.message);
                resetAnalyzeBtn();
            }
        }

        function applyAnalysisResult(result, options = { persist: true }) {
            const analyzeBtn = document.getElementById('analyze-btn');
            const progressText = document.getElementById('progress-text');

            if (!result || !Array.isArray(result.nodes) || !Array.isArray(result.links)) {
                throw new Error('分析结果格式不完整，请重试。');
            }

            // 旧缓存也经过同一层防御性清洗，不要求用户必须重新分析才能去掉孤点。
            result = sanitizeAnalysisResult(result);

            // 替换数据
            allNodes = result.nodes;
            allLinks = result.links;
            CATEGORIES = DYNAMIC_CATEGORIES;
            isDynamicMode = true;
            currentAnalysisResult = result;
            assignDynamicBranchColors(result);

            // 同步更新 nodeMap（buildRelationStory 依赖）
            _nodeMap.clear();
            allNodes.forEach(n => _nodeMap.set(n.id, n));

            // 更新 UI
            const overview = result.overview || {};
            const bookTitle = resolveBookTitle(result);
            const title = `✨ ${bookTitle} · ${overview.total_entities}人物 / ${overview.total_relationships}关系`;
            document.getElementById('info').textContent = title;
            document.getElementById('info').title = overview.protagonist
                ? `主角：${overview.protagonist}`
                : '';

            // 小说模式使用后端从章节/文本位置提取出的剧情阶段。
            const phases = Array.isArray(result.phases) ? result.phases : [];
            renderEraButtons(phases, true);

            // 重建图谱
            buildGraph('all');

            // 重置按钮状态
            analyzeBtn.disabled = false;
            analyzeBtn.textContent = '开始分析人物关系';
            const warning = Array.isArray(overview.warnings) && overview.warnings.length
                ? `；注意：${overview.warnings.join('；')}`
                : '';
            progressText.textContent = `完成！提取了 ${result.nodes.length} 个人物，${result.links.length} 条关系${warning}`;
            document.getElementById('export-btn').disabled = false;
            if (options.persist !== false) {
                const cached = cacheAnalysis(result);
                document.getElementById('restore-last-btn').disabled = !cached && !readCachedAnalysis();
            }

            console.log('分析结果已应用:', overview);
        }

